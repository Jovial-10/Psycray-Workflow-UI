/**
 * ICP assistant: turns the model's reading of a natural-language instruction
 * into a reviewable proposal. The model never changes a configuration:
 *
 *   1. The model returns a list of changes in a closed vocabulary (below).
 *   2. `parseAssistantOutput` validates every change strictly. Anything
 *      unknown, malformed or out of range is rejected and reported, never
 *      applied.
 *   3. `buildProposal` applies the valid changes to the current draft with
 *      plain code, keeps everything else as it was, flags contradictions,
 *      suggests a rebalance when weights don't total 100% (never silently),
 *      and validates the result with the same rules as manual editing.
 *
 * Runs in n8n (generated by `npm run sync:n8n`, like the scoring engine) and
 * in the frontend's sample mode. No imports at runtime beyond the engine and
 * weight helpers, which are inlined into the n8n node.
 */
import {
  CRITERIA,
  DIGITAL_NEEDS,
  GROWTH_SIGNALS,
  INDUSTRY_CATEGORIES,
  OWNER_TYPES,
  REQUIREMENT_LABELS,
  describeConfigChanges,
  normalizeConfig,
  normalizeCountry,
  validateConfig,
  type CriterionKey,
  type DigitalNeedType,
  type GrowthSignalType,
  type IcpConfig,
  type IndustryCategory,
  type OwnerType,
  type RequirementKey,
  type SizeBand,
} from "./icpEngine.ts"
import { fillToHundred, totalWeight } from "./weights.ts"

export const INSTRUCTION_MIN = 3
export const INSTRUCTION_MAX = 1000
/** Rate limits for interpretation requests (whole app; there are no user accounts). */
export const ASSISTANT_LIMITS = { perMinute: 10, perDay: 150 }

/** For vague wording: which way the user asked the value to move. Checked against the proposed number. */
export type Direction = "increase" | "decrease"
const DIRECTIONS: Direction[] = ["increase", "decrease"]

export type IndustryLevel = "core" | "partial" | "low" | "none"
const LEVEL_FIT: Record<IndustryLevel, number> = { core: 1, partial: 0.5, low: 0.25, none: 0 }

export type AssistantChange =
  | { op: "set_weight"; criterion: CriterionKey; percent: number; interpreted: boolean; direction: Direction | null }
  | { op: "set_baseline"; value: number; interpreted: boolean; direction: Direction | null }
  | { op: "set_industry"; category: IndustryCategory; level: IndustryLevel }
  | { op: "set_size_band"; min: number; max: number | null; fit_percent: number }
  | { op: "set_digital_need"; need: DigitalNeedType; enabled: boolean }
  | { op: "set_growth_signal"; signal: GrowthSignalType; strength_percent: number }
  | { op: "set_growth_window"; months: number }
  | { op: "set_owner_type"; owner: OwnerType; enabled: boolean }
  | { op: "set_countries"; countries: string[] }
  | { op: "set_requirement"; requirement: RequirementKey; enabled: boolean; value: number | null }

export interface ParsedOutput {
  changes: AssistantChange[]
  /** Changes the model returned that were not valid, with the reason. Never applied. */
  rejected: string[]
  ambiguities: string[]
  contradictions: string[]
  unsupported: string[]
  summary: string
}

export interface Proposal {
  /** The draft with the requested changes, exactly as asked (weights may not total 100). */
  requested: IcpConfig
  requestedTotal: number
  /** Present when the requested weights don't total 100: a valid alternative and what it changes. */
  rebalance: { config: IcpConfig; changes: string[] } | { error: string } | null
  /** What differs from the current draft, in plain words. */
  changes: { kind: string; text: string }[]
  /** Validation errors of the requested config (same rules as manual editing). */
  errors: string[]
  /** Interpretations to confirm: vague wording read as a number, etc. */
  warnings: string[]
  contradictions: string[]
  unsupported: string[]
  rejected: string[]
  summary: string
  /** The model's changes, as applied (for display and tests). */
  applied: AssistantChange[]
}

