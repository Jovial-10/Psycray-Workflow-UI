/** Inserts a band, trimming any existing band it overlaps so ranges never overlap. */
function withBand(bands: SizeBand[], band: SizeBand): SizeBand[] {
  const hi = band.max ?? Infinity
  const out: SizeBand[] = []
  for (const b of bands) {
    const bHi = b.max ?? Infinity
    if (bHi < band.min || b.min > hi) {
      out.push(b)
      continue
    }
    if (b.min < band.min) out.push({ ...b, max: band.min - 1 })
    if (bHi > hi) out.push({ ...b, min: hi + 1 })
  }
  out.push(band)
  return out.sort((a, b) => a.min - b.min)
}

/** A key per configuration field, used to spot two changes to the same thing. */
function fieldOf(c: AssistantChange): string {
  switch (c.op) {
    case "set_weight": return `weight:${c.criterion}`
    case "set_baseline": return "baseline"
    case "set_industry": return `industry:${c.category}`
    case "set_size_band": return `size:${c.min}-${c.max ?? ""}`
    case "set_digital_need": return `need:${c.need}`
    case "set_growth_signal": return `signal:${c.signal}`
    case "set_growth_window": return "growth_window"
    case "set_owner_type": return `owner:${c.owner}`
    case "set_countries": return "countries"
    case "set_requirement": return `requirement:${c.requirement}`
  }
}

const describe = (c: AssistantChange) => JSON.stringify(c)

/**
 * Applies validated changes to the current draft and builds the proposal.
 * Pure and deterministic. Nothing here publishes or saves.
 */
export function buildProposal(currentRaw: IcpConfig, parsed: ParsedOutput): Proposal {
  const current = normalizeConfig(currentRaw)
  const next = normalizeConfig(JSON.parse(JSON.stringify(current)))
  const contradictions = [...parsed.contradictions]
  const warnings = [...parsed.ambiguities]

  // Two different values for the same field: report it and leave that field alone
  const byField = new Map<string, AssistantChange[]>()
  for (const c of parsed.changes) byField.set(fieldOf(c), [...(byField.get(fieldOf(c)) ?? []), c])
  const conflicted = new Set<string>()
  for (const [field, list] of byField) {
    if (new Set(list.map(describe)).size > 1) {
      conflicted.add(field)
      contradictions.push(`Conflicting values for ${field.replace(":", " ")}; left unchanged so you can decide.`)
    }
  }
  const applied = uniqueChanges(parsed.changes.filter((c) => !conflicted.has(fieldOf(c))))

  const setWeights = new Set<CriterionKey>()
  for (const c of applied) {
    switch (c.op) {
      case "set_weight": {
        const label = CRITERIA.find((x) => x.key === c.criterion)!.label
        const was = current.weights[c.criterion]
        const wrongWay = wrongDirection(c.direction, was, c.percent)
        if (wrongWay) {
          // The number contradicts the wording (e.g. "less important" but higher): don't apply it
          contradictions.push(`You asked to ${c.direction} ${label}, but the proposed ${c.percent}% isn't ${c.direction === "decrease" ? "lower" : "higher"} than ${was}%${wrongWay === "at_limit" ? ` (${was}% is already the ${c.direction === "decrease" ? "minimum" : "maximum"})` : ""}. Left at ${was}%.`)
          break
        }
        next.weights[c.criterion] = c.percent
        setWeights.add(c.criterion)
        if (c.interpreted) warnings.push(`${label} ${was}% → ${c.percent}% is an interpretation of your wording; check the number.`)
        break
      }
      case "set_baseline": {
        const wrongWay = wrongDirection(c.direction, current.baseline, c.value)
        if (wrongWay) {
          contradictions.push(`You asked to ${c.direction} the baseline, but the proposed ${c.value} isn't ${c.direction === "decrease" ? "lower" : "higher"} than ${current.baseline}. Left at ${current.baseline}.`)
          break
        }
        next.baseline = c.value
        if (c.interpreted) warnings.push(`Baseline ${current.baseline} → ${c.value} is an interpretation of your wording; check the number.`)
        break
      }
      case "set_industry":
        next.industryFit = { ...next.industryFit, [c.category]: LEVEL_FIT[c.level] }
        break
      case "set_size_band":
        next.sizeBands = withBand(next.sizeBands, { min: c.min, max: c.max, fraction: c.fit_percent / 100 })
        break
      case "set_digital_need":
        next.digitalOpportunity.types = A_NEED_KEYS.filter((k) => (k === c.need ? c.enabled : next.digitalOpportunity.types.includes(k)))
        break
      case "set_growth_signal":
        next.growthSignalStrength[c.signal] = c.strength_percent / 100
        break
      case "set_growth_window":
        next.growthWindowMonths = c.months
        break
      case "set_owner_type":
        next.projectOwnership.types = A_OWNER_KEYS.filter((k) => (k === c.owner ? c.enabled : next.projectOwnership.types.includes(k)))
        break
      case "set_countries":
        next.geography = { countries: c.countries }
        break
      case "set_requirement": {
        const r = next.requirements
        if (c.requirement === "min_employees") r.min_employees = { enabled: c.enabled, value: c.value ?? r.min_employees.value }
        else if (c.requirement === "min_revenue") r.min_revenue = { enabled: c.enabled, usd: c.value ?? r.min_revenue.usd }
        else r[c.requirement] = { enabled: c.enabled }
        if (c.enabled && c.value === null && (c.requirement === "min_employees" || c.requirement === "min_revenue")) {
          warnings.push(`No threshold was given for "${c.requirement === "min_employees" ? "minimum employees" : "minimum revenue"}"; the current value is kept.`)
        }
        break
      }
    }
  }

  const requestedTotal = totalWeight(next.weights)
  let rebalance: Proposal["rebalance"] = null
  if (requestedTotal !== 100) {
    const filled = fillToHundred(next.weights, setWeights)
    rebalance = "error" in filled ? filled : { config: { ...next, weights: filled.weights }, changes: filled.changes }
  }

  return {
    requested: next,
    requestedTotal,
    rebalance,
    changes: describeConfigChanges(current, next),
    errors: validateConfig(next),
    warnings,
    contradictions,
    unsupported: parsed.unsupported,
    rejected: parsed.rejected,
    summary: parsed.summary,
    applied,
  }
}

/** "at_limit" when the value can't move that way at all, "wrong" when it moved the other way, null when fine. */
function wrongDirection(direction: Direction | null, was: number, next: number): "wrong" | "at_limit" | null {
  if (!direction) return null
  if (direction === "decrease" && next >= was) return was === 0 ? "at_limit" : "wrong"
  if (direction === "increase" && next <= was) return was === 100 ? "at_limit" : "wrong"
  return null
}

function uniqueChanges(list: AssistantChange[]): AssistantChange[] {
  const seen = new Set<string>()
  return list.filter((c) => {
    const k = describe(c)
    if (seen.has(k)) return false
    seen.add(k)
    return true
  })
}

/** Checks an instruction before any model call. Returns an error message, or null when fine. */
export function checkInstruction(instruction: unknown): string | null {
  if (typeof instruction !== "string") return "Describe the change you want."
  const t = instruction.trim()
  if (t.length < INSTRUCTION_MIN) return "Describe the change you want."
  if (t.length > INSTRUCTION_MAX) return `Keep it under ${INSTRUCTION_MAX} characters (this is ${t.length}).`
  return null
}

