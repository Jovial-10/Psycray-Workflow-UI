// Private names start with "A_" or are unique to this file: n8n inlines this
// module after the engine, so a shared name would be a redeclaration error.
const keysOf = <K extends string>(list: { key: K }[]) => list.map((x) => x.key)
const A_CRITERION_KEYS = keysOf(CRITERIA)
const A_INDUSTRY_KEYS = keysOf(INDUSTRY_CATEGORIES)
const A_NEED_KEYS = keysOf(DIGITAL_NEEDS)
const A_SIGNAL_KEYS = keysOf(GROWTH_SIGNALS)
const A_OWNER_KEYS = keysOf(OWNER_TYPES)
const A_REQ_KEYS = keysOf(REQUIREMENT_LABELS)
const LEVELS: IndustryLevel[] = ["core", "partial", "low", "none"]

/** The only fields each change may carry. Anything else makes the change invalid. */
const ALLOWED_FIELDS: Record<AssistantChange["op"], string[]> = {
  set_weight: ["criterion", "percent", "interpreted", "direction"],
  set_baseline: ["value", "interpreted", "direction"],
  set_industry: ["category", "level"],
  set_size_band: ["min", "max", "fit_percent"],
  set_digital_need: ["need", "enabled"],
  set_growth_signal: ["signal", "strength_percent"],
  set_growth_window: ["months"],
  set_owner_type: ["owner", "enabled"],
  set_countries: ["countries"],
  set_requirement: ["requirement", "enabled", "value"],
}

function texts(value: unknown, max = 8): string[] {
  return Array.isArray(value)
    ? value
        .filter((v): v is string => typeof v === "string" && v.trim() !== "")
        .map((v) => v.replace(/\s+/g, " ").trim().slice(0, 300))
        .slice(0, max)
    : []
}

const directionOf = (v: unknown): Direction | null => (DIRECTIONS.includes(v as Direction) ? (v as Direction) : null)
const isInt = (v: unknown, lo: number, hi: number): v is number => typeof v === "number" && Number.isInteger(v) && v >= lo && v <= hi
const isNum = (v: unknown, lo: number, hi: number): v is number => typeof v === "number" && Number.isFinite(v) && v >= lo && v <= hi

/** Validates one change; returns it typed, or a reason it was rejected. */
function checkChange(raw: unknown): AssistantChange | string {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return "not an object"
  const c = raw as Record<string, unknown>
  const op = c.op
  if (typeof op !== "string" || !(op in ALLOWED_FIELDS)) return `unknown change type ${JSON.stringify(op)}`
  const extra = Object.keys(c).filter((k) => k !== "op" && !ALLOWED_FIELDS[op as AssistantChange["op"]].includes(k))
  if (extra.length) return `${op} has unsupported fields: ${extra.join(", ")}`
  const has = (k: string) => c[k] !== undefined

  switch (op) {
    case "set_weight":
      if (!A_CRITERION_KEYS.includes(c.criterion as CriterionKey)) return `set_weight: unknown criterion ${JSON.stringify(c.criterion)}`
      if (!isInt(c.percent, 0, 100)) return `set_weight: percent must be a whole number 0–100`
      return { op, criterion: c.criterion as CriterionKey, percent: c.percent, interpreted: c.interpreted === true, direction: directionOf(c.direction) }
    case "set_baseline":
      if (!isInt(c.value, 0, 90)) return "set_baseline: value must be a whole number 0–90"
      return { op, value: c.value, interpreted: c.interpreted === true, direction: directionOf(c.direction) }
    case "set_industry":
      if (!A_INDUSTRY_KEYS.includes(c.category as IndustryCategory)) return `set_industry: unknown category ${JSON.stringify(c.category)}`
      if (!LEVELS.includes(c.level as IndustryLevel)) return `set_industry: level must be one of ${LEVELS.join(", ")}`
      return { op, category: c.category as IndustryCategory, level: c.level as IndustryLevel }
    case "set_size_band": {
      if (!isInt(c.min, 1, 10_000_000)) return "set_size_band: min must be a whole number ≥ 1"
      const max = c.max === null || !has("max") ? null : c.max
      if (max !== null && !isInt(max, c.min, 10_000_000)) return "set_size_band: max must be ≥ min (or null)"
      if (!isInt(c.fit_percent, 0, 100)) return "set_size_band: fit_percent must be 0–100"
      return { op, min: c.min, max, fit_percent: c.fit_percent }
    }
    case "set_digital_need":
      if (!A_NEED_KEYS.includes(c.need as DigitalNeedType)) return `set_digital_need: unknown need ${JSON.stringify(c.need)}`
      if (typeof c.enabled !== "boolean") return "set_digital_need: enabled must be true or false"
      return { op, need: c.need as DigitalNeedType, enabled: c.enabled }
    case "set_growth_signal":
      if (!A_SIGNAL_KEYS.includes(c.signal as GrowthSignalType)) return `set_growth_signal: unknown signal ${JSON.stringify(c.signal)}`
      if (!isInt(c.strength_percent, 0, 100)) return "set_growth_signal: strength_percent must be 0–100"
      return { op, signal: c.signal as GrowthSignalType, strength_percent: c.strength_percent }
    case "set_growth_window":
      if (!isInt(c.months, 1, 60)) return "set_growth_window: months must be 1–60"
      return { op, months: c.months }
    case "set_owner_type":
      if (!A_OWNER_KEYS.includes(c.owner as OwnerType)) return `set_owner_type: unknown owner ${JSON.stringify(c.owner)}`
      if (typeof c.enabled !== "boolean") return "set_owner_type: enabled must be true or false"
      return { op, owner: c.owner as OwnerType, enabled: c.enabled }
    case "set_countries": {
      const countries = texts(c.countries, 20).map(normalizeCountry).filter(Boolean)
      if (countries.length === 0 && !(Array.isArray(c.countries) && c.countries.length === 0)) return "set_countries: countries must be a list of names"
      return { op, countries: [...new Set(countries)] }
    }
    case "set_requirement": {
      if (!A_REQ_KEYS.includes(c.requirement as RequirementKey)) return `set_requirement: unknown requirement ${JSON.stringify(c.requirement)}`
      if (typeof c.enabled !== "boolean") return "set_requirement: enabled must be true or false"
      const value = c.value === undefined || c.value === null ? null : c.value
      const req = c.requirement as RequirementKey
      if (value !== null) {
        if (req === "min_employees" && !isInt(value, 1, 10_000_000)) return "set_requirement: minimum employees must be a whole number ≥ 1"
        if (req === "min_revenue" && !isNum(value, 1, 1e13)) return "set_requirement: minimum revenue must be a positive dollar amount"
        if (req === "location" || req === "b2b") return `set_requirement: ${req} takes no value`
      }
      return { op, requirement: req, enabled: c.enabled, value: value as number | null }
    }
  }
  return "unknown change"
}

/** Extracts the JSON object from model text and validates it. Never throws. */
export function parseAssistantOutput(text: unknown): { ok: true; output: ParsedOutput } | { ok: false; error: string } {
  if (typeof text !== "string" || !text.trim()) return { ok: false, error: "The assistant returned an empty response." }
  const cleaned = text.replace(/```json\s?|```/g, "").trim()
  const start = cleaned.indexOf("{")
  const end = cleaned.lastIndexOf("}")
  if (start === -1 || end <= start) return { ok: false, error: "The assistant's response wasn't valid JSON." }
  let raw: unknown
  try {
    raw = JSON.parse(cleaned.slice(start, end + 1))
  } catch {
    return { ok: false, error: "The assistant's response wasn't valid JSON." }
  }
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { ok: false, error: "The assistant's response had the wrong shape." }
  const r = raw as Record<string, unknown>
  if (!Array.isArray(r.changes)) return { ok: false, error: "The assistant's response had no list of changes." }

  const changes: AssistantChange[] = []
  const rejected: string[] = []
  for (const item of r.changes.slice(0, 40)) {
    const checked = checkChange(item)
    if (typeof checked === "string") rejected.push(checked)
    else changes.push(checked)
  }
  return {
    ok: true,
    output: {
      changes,
      rejected,
      ambiguities: texts(r.ambiguities),
      contradictions: texts(r.contradictions),
      unsupported: texts(r.unsupported),
      summary: typeof r.summary === "string" ? r.summary.replace(/\s+/g, " ").trim().slice(0, 400) : "",
    },
  }
}

